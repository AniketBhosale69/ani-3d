#!/usr/bin/env node
// One-off migration: read both Supabase tables, write seed.sql for D1.
//
//   SUPABASE_KEY=<anon-key> node tools/export-supabase.mjs
//   node tools/export-supabase.mjs <anon-key>
//
// Then:  npx wrangler d1 execute ani3d --remote --file=seed.sql
//
// The key is no longer read out of the HTML — it has been removed from the
// pages, and it should be rotated once the migration is done.

import { writeFileSync } from 'node:fs';

const PROJECT = 'https://iibmcpoqyctytzlclaon.supabase.co';
const TABLES = [
  { name: 'videos', category: 'classic' },
  { name: 'outframe_videos', category: 'outframe' },
];

const key = process.argv[2] || process.env.SUPABASE_KEY;
if (!key) {
  console.error('Usage: SUPABASE_KEY=<anon-key> node tools/export-supabase.mjs');
  console.error('Find the key in the Supabase dashboard under Settings > API.');
  process.exit(1);
}

// SQLite string literal: double up single quotes. Everything goes through this,
// so quotes and newlines inside the long Owl3D descriptions stay intact.
const q = (v) => (v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || v === '' ? 'NULL' : Number(v));

const lines = [
  '-- Generated by tools/export-supabase.mjs — do not edit by hand.',
  'PRAGMA foreign_keys=OFF;',
  'BEGIN TRANSACTION;',
];
let total = 0;

for (const { name, category } of TABLES) {
  const res = await fetch(`${PROJECT}/rest/v1/${name}?select=*&order=created_at.asc`, {
    headers: { apikey: key, Authorization: `Bearer ${key}` },
  });
  if (!res.ok) {
    console.error(`Failed to read ${name}: HTTP ${res.status} ${await res.text()}`);
    process.exit(1);
  }
  const rows = await res.json();
  console.log(`${name.padEnd(16)} ${rows.length} rows -> category '${category}'`);
  total += rows.length;

  lines.push('', `-- ${name} (${rows.length} rows)`);
  for (const r of rows) {
    lines.push(
      `INSERT INTO videos (category, title, content_type, genre, language, year, ` +
      `stream_url, download_url, thumb, description, created_at) VALUES (` +
      [
        q(category), q(r.title), q(r.content_type), q(r.genre), q(r.language), n(r.year),
        q(r.stream_url), q(r.download_url), q(r.thumb), q(r.description),
        q(r.created_at || new Date().toISOString()),
      ].join(', ') + ');',
    );
  }
}

// ---- blog_posts -> posts ----
{
  const res = await fetch(`${PROJECT}/rest/v1/blog_posts?select=*&order=created_at.asc`, {
    headers: { apikey: key, Authorization: `Bearer ${key}` },
  });
  if (!res.ok) {
    console.error(`Failed to read blog_posts: HTTP ${res.status} ${await res.text()}`);
    process.exit(1);
  }
  const rows = await res.json();
  console.log(`${'blog_posts'.padEnd(16)} ${rows.length} rows -> posts`);
  total += rows.length;

  lines.push('', `-- blog_posts (${rows.length} rows)`);
  for (const r of rows) {
    lines.push(
      `INSERT INTO posts (title, slug, category, excerpt, content, image, author, date, status, created_at) VALUES (` +
      [
        q(r.title), q(r.slug), q(r.category), q(r.excerpt), q(r.content), q(r.image),
        q(r.author), q(r.date), q(r.status === 'published' ? 'published' : 'draft'),
        q(r.created_at || new Date().toISOString()),
      ].join(', ') + ');',
    );
  }
}

lines.push('', 'COMMIT;', '');
writeFileSync('seed.sql', lines.join('\n'));
console.log(`\nWrote seed.sql — ${total} rows total.`);
